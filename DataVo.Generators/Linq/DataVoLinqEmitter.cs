using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace DataVo.Generators.Linq;

/// <summary>Writes the interceptors for a compilation's table queries. The members stay within C# 9.</summary>
internal static class DataVoLinqEmitter
{
    /// <summary>The namespace a project must list in <c>InterceptorsNamespaces</c>.</summary>
    public const string Namespace = "DataVo.Generated";

    private const string Core = "global::DataVo.Core.";
    private const string Parameter = Core + "DataVoQueryParameter";
    private const string Statement = Core + "DataVoPreparedStatement";
    private const string Result = Core + "Contracts.Results.QueryResult";

    public static string Emit(IReadOnlyList<LinqSite> sites, bool fileLocalTypes)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine("#pragma warning disable").AppendLine();
        code.AppendLine($$"""
            namespace System.Runtime.CompilerServices
            {
                [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
                {{(fileLocalTypes ? "file" : "internal")}} sealed class InterceptsLocationAttribute : global::System.Attribute
                {
                    public InterceptsLocationAttribute(int version, string data)
                    {
                    }

                    public InterceptsLocationAttribute(string filePath, int line, int character)
                    {
                    }
                }
            }

            namespace {{Namespace}}
            {
                /// <summary>Routes DataVoTable queries to statements prepared from their lambdas at compile time.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("DataVo.Generators", "1.0")]
                internal static class DataVoLinqInterceptors
                {
            """);

        for (int index = 0; index < sites.Count; index++)
        {
            EmitSite(code, sites[index], index.ToString(CultureInfo.InvariantCulture));
        }

        code.AppendLine("    }").AppendLine("}");
        return code.ToString();
    }

    private static void EmitSite(StringBuilder code, LinqSite site, string id)
    {
        string model = site.ModelType;
        string state = site.StateType;
        string plan = $"{Core}DataVoLinqPlan<{model}, {state}>";
        string table = $"{Core}DataVoTable<{model}>";
        string returns = site.Method == "Where"
            ? $"{Core}DataVoQuery<{model}, {state}>"
            : model + (site.ModelIsReferenceType ? "?" : string.Empty);
        string location = site.Location.Version > 0
            ? $"{site.Location.Version.ToString(CultureInfo.InvariantCulture)}, {SymbolDisplay.FormatLiteral(site.Location.Data, quote: true)}"
            : $"{SymbolDisplay.FormatLiteral(site.Location.Path, quote: true)}, {site.Location.Line.ToString(CultureInfo.InvariantCulture)}, {site.Location.Column.ToString(CultureInfo.InvariantCulture)}";
        LinqParameter[] parameters = [.. site.Parameters];
        string[] guards = [.. parameters.Where(static parameter => parameter.Guard is not null).Select(static parameter => parameter.Guard!)];

        code.AppendLine($$"""
                    private sealed class Plan{{id}} : {{plan}}
                    {
                        public static readonly Plan{{id}} Instance = new Plan{{id}}();

                        private Plan{{id}}()
                            : base({{SymbolDisplay.FormatLiteral(site.Where, quote: true)}}, {{(site.Unique ? "true" : "false")}})
                        {
                        }

            """);

        if (guards.Length > 0)
        {
            code.AppendLine($$"""
                            protected override bool CanBind({{state}} state)
                            {
                                return {{string.Join(" && ", guards)}};
                            }

                """);
        }

        code.AppendLine($"            protected override {Result} Run({Statement} statement, {state} state, bool borrowed)");
        code.AppendLine("            {");
        string[] names = [.. parameters.Select(static (_, index) => "p" + index.ToString(CultureInfo.InvariantCulture))];
        if (parameters.Length <= 4)
        {
            for (int index = 0; index < parameters.Length; index++)
            {
                code.AppendLine($"                {Parameter} {names[index]} = {Bind(parameters[index], names[index])};");
            }

            string arguments = string.Join(", ", names);
            code.AppendLine($"                return borrowed ? statement.ExecuteBorrowed({arguments}) : statement.Execute({arguments});");
        }
        else
        {
            code.AppendLine($"                {Parameter}[] parameters = new {Parameter}[]");
            code.AppendLine("                {");
            for (int index = 0; index < parameters.Length; index++)
            {
                code.AppendLine($"                    {Bind(parameters[index], names[index])},");
            }

            code.AppendLine("                };");
            code.AppendLine($"                return borrowed ? statement.ExecuteBorrowed(new global::System.ReadOnlySpan<{Parameter}>(parameters)) : statement.Execute(parameters);");
        }

        code.AppendLine("            }");
        code.AppendLine("        }").AppendLine();

        code.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({location})]");
        if (site.Stateful)
        {
            code.AppendLine($"        public static {returns} {site.Method}{id}(this {table} table, {state} state, global::System.Func<{model}, {state}, bool> predicate)");
            code.AppendLine("        {");
            code.AppendLine($"            return Plan{id}.Instance.{site.Method}(table, state, predicate);");
        }
        else
        {
            code.AppendLine($"        public static {returns} {site.Method}{id}(this {table} table, {state} predicate)");
            code.AppendLine("        {");
            code.AppendLine($"            return Plan{id}.Instance.{site.Method}(table, predicate, {table}.InvokePredicate);");
        }

        code.AppendLine("        }").AppendLine();
    }

    private static string Bind(LinqParameter parameter, string name) => parameter.UsesObjectParameter
        ? $"{Parameter}.FromObject(\"{name}\", {parameter.Value})"
        : $"new {Parameter}(\"{name}\", {parameter.Value})";
}
