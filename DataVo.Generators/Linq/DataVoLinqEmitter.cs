using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace DataVo.Generators.Linq;

/// <summary>Writes the interceptors for a compilation's table queries. The members stay within C# 9.</summary>
internal static class DataVoLinqEmitter
{
    /// <summary>The namespace a project must list in <c>InterceptorsNamespaces</c>.</summary>
    public const string Namespace = "DataVo.Generated";

    private const string Core = "global::DataVo.Core.";
    private const string Parameter = Core + "DataVoQueryParameter";
    private const string Statement = Core + "DataVoPreparedStatement";
    private const string Result = Core + "Contracts.Results.QueryResult";

    public static string Emit(IReadOnlyList<LinqSite> sites, IReadOnlyList<LinqSumSite> sums, IReadOnlyList<LinqExtremeSite> extremes, bool fileLocalTypes)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine("#pragma warning disable").AppendLine();
        code.AppendLine($$"""
            namespace System.Runtime.CompilerServices
            {
                [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
                {{(fileLocalTypes ? "file" : "internal")}} sealed class InterceptsLocationAttribute : global::System.Attribute
                {
                    public InterceptsLocationAttribute(int version, string data)
                    {
                    }

                    public InterceptsLocationAttribute(string filePath, int line, int character)
                    {
                    }
                }
            }

            namespace {{Namespace}}
            {
                /// <summary>Routes DataVoTable queries to statements prepared from their lambdas at compile time.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("DataVo.Generators", "1.0")]
                internal static class DataVoLinqInterceptors
                {
            """);

        for (int index = 0; index < sites.Count; index++)
        {
            EmitSite(code, sites[index], index.ToString(CultureInfo.InvariantCulture));
        }

        for (int index = 0; index < sums.Count; index++)
        {
            EmitSum(code, sums[index], index.ToString(CultureInfo.InvariantCulture));
        }

        for (int index = 0; index < extremes.Count; index++)
        {
            EmitExtreme(code, extremes[index], index.ToString(CultureInfo.InvariantCulture));
        }

        code.AppendLine("    }").AppendLine("}");
        return code.ToString();
    }

    /// <summary>Routes a <c>Sum</c> over one column to the query's plan, which sums it inside the scan when it can.</summary>
    private static void EmitSum(StringBuilder code, LinqSumSite site, string id)
    {
        string query = $"{Core}DataVoQuery<{site.ModelType}, {site.StateType}>";
        string location = Location(site.Location);
        code.AppendLine($"        private static readonly string[] SumColumn{id} = new string[] {{ {SymbolDisplay.FormatLiteral(site.Column, quote: true)} }};");
        code.AppendLine();
        code.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({location})]");
        code.AppendLine($"        public static {site.ValueType} Sum{id}(this in {query} query, global::System.Func<{site.ModelType}, {site.ValueType}> selector)");
        code.AppendLine("        {");
        code.AppendLine($"            return query.{site.RuntimeMethod}(SumColumn{id}, selector);");
        code.AppendLine("        }").AppendLine();
    }

    /// <summary>
    /// Routes a <c>Min</c> or <c>Max</c> over one column to the query's plan, which finds the value inside the scan
    /// when it can. An empty result throws, or is null for a nullable column, as the original call would.
    /// </summary>
    private static void EmitExtreme(StringBuilder code, LinqExtremeSite site, string id)
    {
        string query = $"{Core}DataVoQuery<{site.ModelType}, {site.StateType}>";
        string name = site.Largest ? "Max" : "Min";
        code.AppendLine($"        private static readonly string[] {name}Column{id} = new string[] {{ {SymbolDisplay.FormatLiteral(site.Column, quote: true)} }};");
        code.AppendLine();
        code.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({Location(site.Location)})]");
        code.AppendLine($"        public static {site.ValueType} {name}{id}(this in {query} query, global::System.Func<{site.ModelType}, {site.ValueType}> selector)");
        code.AppendLine("        {");
        code.AppendLine($"            {Core}RowFoldTotals totals;");
        code.AppendLine($"            if (!query.TryFoldColumn({name}Column{id}, {Core}RowFold.{name}, '{site.Kind}', out totals))");
        code.AppendLine("            {");
        code.AppendLine($"                return query.{name}(selector);");
        code.AppendLine("            }");
        code.AppendLine();
        code.AppendLine("            if (totals.Values == 0)");
        code.AppendLine("            {");
        code.AppendLine(site.Nullable
            ? "                return null;"
            : "                throw new global::System.InvalidOperationException(\"Sequence contains no elements\");");
        code.AppendLine("            }");
        code.AppendLine();
        code.AppendLine($"            return {site.Result};");
        code.AppendLine("        }").AppendLine();
    }

    private static string Location(LinqLocation location) => location.Version > 0
        ? $"{location.Version.ToString(CultureInfo.InvariantCulture)}, {SymbolDisplay.FormatLiteral(location.Data, quote: true)}"
        : $"{SymbolDisplay.FormatLiteral(location.Path, quote: true)}, {location.Line.ToString(CultureInfo.InvariantCulture)}, {location.Column.ToString(CultureInfo.InvariantCulture)}";

    private static void EmitSite(StringBuilder code, LinqSite site, string id)
    {
        string model = site.ModelType;
        string state = site.StateType;
        string plan = $"{Core}DataVoLinqPlan<{model}, {state}>";
        string table = $"{Core}DataVoTable<{model}>";
        string returns = site.Method == "Where"
            ? $"{Core}DataVoQuery<{model}, {state}>"
            : model + (site.ModelIsReferenceType ? "?" : string.Empty);
        string location = site.Location.Version > 0
            ? $"{site.Location.Version.ToString(CultureInfo.InvariantCulture)}, {SymbolDisplay.FormatLiteral(site.Location.Data, quote: true)}"
            : $"{SymbolDisplay.FormatLiteral(site.Location.Path, quote: true)}, {site.Location.Line.ToString(CultureInfo.InvariantCulture)}, {site.Location.Column.ToString(CultureInfo.InvariantCulture)}";
        LinqParameter[] parameters = [.. site.Parameters];
        string[] guards = [.. parameters.Where(static parameter => parameter.Guard is not null).Select(static parameter => parameter.Guard!)];

        code.AppendLine($$"""
                    private sealed class Plan{{id}} : {{plan}}
                    {
                        public static readonly Plan{{id}} Instance = new Plan{{id}}();

                        private Plan{{id}}()
                            : base({{SymbolDisplay.FormatLiteral(site.Where, quote: true)}}, {{(site.Unique ? "true" : "false")}})
                        {
                        }

            """);

        if (guards.Length > 0)
        {
            code.AppendLine($$"""
                            protected override bool CanBind({{state}} state)
                            {
                                return {{string.Join(" && ", guards)}};
                            }

                """);
        }

        code.AppendLine($"            protected override {Result} Run({Statement} statement, {state} state, bool borrowed)");
        code.AppendLine("            {");
        string[] names = [.. parameters.Select(static (_, index) => "p" + index.ToString(CultureInfo.InvariantCulture))];
        if (parameters.Length <= 4)
        {
            for (int index = 0; index < parameters.Length; index++)
            {
                code.AppendLine($"                {Parameter} {names[index]} = {Bind(parameters[index], names[index])};");
            }

            string arguments = string.Join(", ", names);
            code.AppendLine($"                return borrowed ? statement.ExecuteBorrowed({arguments}) : statement.Execute({arguments});");
        }
        else
        {
            code.AppendLine($"                {Parameter}[] parameters = new {Parameter}[]");
            code.AppendLine("                {");
            for (int index = 0; index < parameters.Length; index++)
            {
                code.AppendLine($"                    {Bind(parameters[index], names[index])},");
            }

            code.AppendLine("                };");
            code.AppendLine($"                return borrowed ? statement.ExecuteBorrowed(new global::System.ReadOnlySpan<{Parameter}>(parameters)) : statement.Execute(parameters);");
        }

        code.AppendLine("            }").AppendLine();
        code.AppendLine($"            protected override {Parameter}[] Parameters({state} state)");
        code.AppendLine("            {");
        if (parameters.Length == 0)
        {
            code.AppendLine($"                return global::System.Array.Empty<{Parameter}>();");
        }
        else
        {
            code.AppendLine($"                return new {Parameter}[]");
            code.AppendLine("                {");
            for (int index = 0; index < parameters.Length; index++)
            {
                code.AppendLine($"                    {Bind(parameters[index], names[index])},");
            }

            code.AppendLine("                };");
        }

        code.AppendLine("            }");
        if (site.Kernel is { } kernel)
        {
            EmitKernel(code, site, kernel, parameters, table, state);
        }

        code.AppendLine("        }").AppendLine();

        code.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({location})]");
        if (site.Stateful)
        {
            code.AppendLine($"        public static {returns} {site.Method}{id}(this {table} table, {state} state, global::System.Func<{model}, {state}, bool> predicate)");
            code.AppendLine("        {");
            code.AppendLine($"            return Plan{id}.Instance.{site.Method}(table, state, predicate);");
        }
        else
        {
            code.AppendLine($"        public static {returns} {site.Method}{id}(this {table} table, {state} predicate)");
            code.AppendLine("        {");
            code.AppendLine($"            return Plan{id}.Instance.{site.Method}(table, predicate, {table}.InvokePredicate);");
        }

        code.AppendLine("        }").AppendLine();
    }

    /// <summary>
    /// Writes the condition as a struct over <c>RowRef</c> and the override that counts with it. The scan is
    /// generic over the struct, so the condition is compiled into the loop: no row objects, no delegate calls.
    /// The struct also describes itself step by step, which is how a table with a columnar index runs it.
    /// </summary>
    private static void EmitKernel(StringBuilder code, LinqSite site, LinqKernel kernel, LinqParameter[] parameters, string table, string state)
    {
        string[] columns = [.. kernel.Columns];
        code.AppendLine();
        code.AppendLine($"            private static readonly string[] Columns = new string[] {{ {string.Join(", ", columns.Select(static column => SymbolDisplay.FormatLiteral(column, quote: true)))} }};");
        code.AppendLine($"            private const string Kinds = {SymbolDisplay.FormatLiteral(kernel.Kinds, quote: true)};");
        code.AppendLine();
        code.AppendLine($"            private struct Kernel : {Core}IRowRefFilter, {Core}IColumnarFilter");
        code.AppendLine("            {");
        for (int index = 0; index < columns.Length; index++)
        {
            code.AppendLine($"                private int c{index.ToString(CultureInfo.InvariantCulture)};");
            code.AppendLine($"                private int o{index.ToString(CultureInfo.InvariantCulture)};");
        }

        for (int index = 0; index < parameters.Length; index++)
        {
            code.AppendLine($"                public {parameters[index].KernelType} p{index.ToString(CultureInfo.InvariantCulture)};");
        }

        code.AppendLine();
        code.AppendLine("                public void Bind(global::System.ReadOnlySpan<int> ordinals)");
        code.AppendLine("                {");
        for (int index = 0; index < columns.Length; index++)
        {
            string number = index.ToString(CultureInfo.InvariantCulture);
            code.AppendLine($"                    c{number} = ordinals[{number}];");
        }

        code.AppendLine("                }");
        code.AppendLine();
        code.AppendLine("                public void BindOffsets(global::System.ReadOnlySpan<int> offsets)");
        code.AppendLine("                {");
        for (int index = 0; index < columns.Length; index++)
        {
            string number = index.ToString(CultureInfo.InvariantCulture);
            code.AppendLine($"                    o{number} = offsets[{number}];");
        }

        code.AppendLine("                }");
        code.AppendLine();
        code.AppendLine($"                public bool Matches(in {Core}RowRef row)");
        code.AppendLine("                {");
        code.AppendLine($"                    return {kernel.Expression};");
        code.AppendLine("                }");
        code.AppendLine();
        code.AppendLine("                public bool MatchesBytes(global::System.ReadOnlySpan<byte> row)");
        code.AppendLine("                {");
        code.AppendLine($"                    return {kernel.BytesExpression};");
        code.AppendLine("                }");
        code.AppendLine();
        code.AppendLine($"                public bool MatchesCells(global::System.ReadOnlySpan<{Core}Runtime.Reactive.CellValue> cells)");
        code.AppendLine("                {");
        code.AppendLine($"                    return {kernel.CellsExpression};");
        code.AppendLine("                }");
        code.AppendLine();
        code.AppendLine($"                public void Describe(ref {Core}ColumnarPredicateBuilder builder)");
        code.AppendLine("                {");
        foreach (string step in kernel.Describe)
        {
            code.AppendLine($"                    {step}");
        }

        code.AppendLine("                }");
        code.AppendLine("            }");
        code.AppendLine();
        code.AppendLine($"            protected override bool TryCount({table} table, {state} state, int limit, out int count)");
        code.AppendLine("            {");
        code.AppendLine("                Kernel kernel = default(Kernel);");
        for (int index = 0; index < parameters.Length; index++)
        {
            code.AppendLine($"                kernel.p{index.ToString(CultureInfo.InvariantCulture)} = {parameters[index].Value};");
        }

        code.AppendLine("                count = table.CountMatchingColumnar(Columns, Kinds, ref kernel, limit);");
        code.AppendLine("                return true;");
        code.AppendLine("            }");
        code.AppendLine();
        code.AppendLine($"            protected override bool TryFold({table} table, {state} state, string[] column, {Core}RowFold fold, char kind, out {Core}RowFoldTotals totals)");
        code.AppendLine("            {");
        code.AppendLine("                Kernel kernel = default(Kernel);");
        for (int index = 0; index < parameters.Length; index++)
        {
            code.AppendLine($"                kernel.p{index.ToString(CultureInfo.InvariantCulture)} = {parameters[index].Value};");
        }

        code.AppendLine("                return table.FoldMatchingColumnar(Columns, Kinds, ref kernel, column, fold, kind, out totals);");
        code.AppendLine("            }");
    }

    private static string Bind(LinqParameter parameter, string name) => parameter.UsesObjectParameter
        ? $"{Parameter}.FromObject(\"{name}\", {parameter.Value})"
        : $"new {Parameter}(\"{name}\", {parameter.Value})";
}
