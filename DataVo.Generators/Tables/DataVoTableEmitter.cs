using System.Text;

namespace DataVo.Generators.Tables;

/// <summary>Writes the extension methods for one model. The output stays within C# 9 so Unity can compile it.</summary>
internal static class DataVoTableEmitter
{
    private const string Core = "global::DataVo.Core.";
    private const string Support = Core + "Annotations.DataVoGeneratedTableSupport";
    private const string Parameter = Core + "DataVoQueryParameter";
    private const string Statement = Core + "DataVoPreparedStatement";
    private const string Context = Core + "DataVoContext";

    public static string Emit(TableModel model)
    {
        ColumnModel[] columns = [.. model.Columns];
        ColumnModel key = columns.Single(static column => column.IsPrimaryKey);
        ColumnModel[] values = [.. columns.Where(static column => !column.IsPrimaryKey)];
        string nameList = string.Join(", ", columns.Select(static column => column.PropertyName));
        string access = model.IsPublic ? "public" : "internal";
        string nullableResult = model.FullTypeName + "?";

        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>").AppendLine("#nullable enable").AppendLine();
        if (model.Namespace is not null)
        {
            code.Append("namespace ").AppendLine(model.Namespace).AppendLine("{");
        }

        code.Append("    /// <summary>Generated data access for <see cref=\"").Append(model.FullTypeName).AppendLine("\"/>.</summary>");
        code.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"DataVo.Generators\", \"1.0\")]");
        code.Append("    ").Append(access).Append(" static class ").Append(model.ModelName).AppendLine("DataVoExtensions");
        code.AppendLine("    {");
        EmitStatements(code, model, columns, values, key, nameList);
        EmitReader(code, model, columns);
        EmitEnsure(code, model, columns, key);
        EmitGet(code, model, key, nullableResult);
        EmitInsert(code, model, columns);
        if (values.Length > 0)
        {
            EmitUpdate(code, model, values, key);
        }

        code.AppendLine("    }");
        if (model.Namespace is not null)
        {
            code.AppendLine("}");
        }

        return code.ToString();
    }

    private static void EmitStatements(StringBuilder code, TableModel model, ColumnModel[] columns, ColumnModel[] values, ColumnModel key, string nameList)
    {
        string placeholders = string.Join(", ", columns.Select(static (_, index) => $"@p{index}"));
        string assignments = string.Join(", ", values.Select(static (column, index) => $"{column.PropertyName} = @p{index}"));
        code.AppendLine($$"""
                    private sealed class Statements
                    {
                        public readonly global::System.Guid Session;
                        public readonly {{Statement}} Get;
                        public readonly {{Statement}} Insert;
                        public readonly {{Statement}}? Update;

                        public Statements({{Context}} context)
                        {
                            Session = context.SessionId;
                            Get = context.Prepare("SELECT {{nameList}} FROM {{model.TableName}} WHERE {{key.PropertyName}} = @key");
                            Insert = context.Prepare("INSERT INTO {{model.TableName}} ({{nameList}}) VALUES ({{placeholders}})");
                            Update = {{(values.Length > 0 ? $"context.Prepare(\"UPDATE {model.TableName} SET {assignments} WHERE {key.PropertyName} = @key\")" : "null")}};
                        }
                    }

                    private static readonly global::System.Runtime.CompilerServices.ConditionalWeakTable<{{Context}}, Statements> Cache = new global::System.Runtime.CompilerServices.ConditionalWeakTable<{{Context}}, Statements>();

                    private static Statements StatementsFor({{Context}} context)
                    {
                        if (Cache.TryGetValue(context, out Statements? cached) && cached.Session == context.SessionId)
                        {
                            return cached;
                        }

                        var statements = new Statements(context);
                        Cache.AddOrUpdate(context, statements);
                        return statements;
                    }

            """);
    }

    private static void EmitReader(StringBuilder code, TableModel model, ColumnModel[] columns)
    {
        string[] constructorArguments = [.. model.ConstructorParameters.Select(parameter =>
            ReadExpression(columns.Single(column => column.PropertyName.Equals(parameter, StringComparison.OrdinalIgnoreCase))))];
        string[] initializers = [.. columns
            .Where(static column => column.IsSettable && !column.IsConstructorParameter)
            .Select(static column => $"{column.PropertyName} = {ReadExpression(column)}")];

        code.AppendLine("        private static readonly global::System.Func<global::System.Collections.Generic.Dictionary<string, object?>, " + model.FullTypeName + "> ReadRow = static row =>");
        code.Append("            new ").Append(model.FullTypeName).Append('(').Append(string.Join(", ", constructorArguments)).AppendLine(")");
        code.AppendLine("            {");
        foreach (string initializer in initializers)
        {
            code.Append("                ").Append(initializer).AppendLine(",");
        }

        code.AppendLine("            };").AppendLine();
    }

    private static string ReadExpression(ColumnModel column) =>
        $"{Support}.{column.Type.ReaderMethod}(row[\"{column.PropertyName}\"], \"{column.PropertyName}\"){column.Type.ReadSuffix}";

    private static void EmitEnsure(StringBuilder code, TableModel model, ColumnModel[] columns, ColumnModel key)
    {
        string definitions = string.Join(", ", columns.Select(static column => column.IsPrimaryKey
            ? $"{column.PropertyName} {column.Type.SqlType} PRIMARY KEY"
            : $"{column.PropertyName} {column.Type.SqlType}{(column.IsNullable ? string.Empty : " NOT NULL")}"));
        string typeList = string.Join(", ", columns.Select(static column => $"(\"{column.PropertyName}\", \"{column.Type.SqlType}\")"));
        string indexList = string.Join(", ", columns.Where(static column => column.IsIndexed && !column.IsPrimaryKey).Select(static column => $"\"{column.PropertyName}\""));
        code.AppendLine($$"""
                    /// <summary>Creates the {{model.TableName}} table and its indexes if missing, and verifies an existing table matches the model.</summary>
                    public static void Ensure{{model.ModelName}}Table(this {{Context}} context)
                    {
                        {{Support}}.EnsureTable(
                            context,
                            "{{model.TableName}}",
                            "CREATE TABLE {{model.TableName}} ({{definitions}})",
                            new (string, string)[] { {{typeList}} },
                            new string[] { {{indexList}} });
                    }

            """);
    }

    private static void EmitGet(StringBuilder code, TableModel model, ColumnModel key, string nullableResult)
    {
        string miss = model.IsReferenceType ? "null" : $"({nullableResult})null";
        code.AppendLine($$"""
                    /// <summary>Reads one row by primary key, or returns null when it does not exist.</summary>
                    public static {{nullableResult}} Get{{model.ModelName}}By{{key.PropertyName}}(this {{Context}} context, {{key.TypeName}} key)
                    {
                        global::DataVo.Core.Contracts.Results.QueryResult result = StatementsFor(context).Get.ExecuteBorrowed({{ParameterExpression(key, "key", "key")}});
                        {{Support}}.ThrowIfError(result, "Get{{model.ModelName}}By{{key.PropertyName}}");
                        return result.Data.Count == 0 ? {{miss}} : ReadRow(result.Data[0]);
                    }

            """);
    }

    private static void EmitInsert(StringBuilder code, TableModel model, ColumnModel[] columns)
    {
        string arguments = string.Join(", ", columns.Select(static (column, index) => ParameterExpression(column, $"p{index}", $"entity.{column.PropertyName}")));
        code.AppendLine($$"""
                    /// <summary>Inserts a row.</summary>
                    public static void Insert(this {{Context}} context, {{model.FullTypeName}} entity)
                    {
            {{GuardNull(model)}}
                        {{Support}}.ThrowIfError(StatementsFor(context).Insert.Execute(new {{Parameter}}[] { {{arguments}} }), "Insert {{model.ModelName}}");
                    }

            """);
    }

    private static void EmitUpdate(StringBuilder code, TableModel model, ColumnModel[] values, ColumnModel key)
    {
        string arguments = string.Join(", ", values.Select(static (column, index) => ParameterExpression(column, $"p{index}", $"entity.{column.PropertyName}")));
        code.AppendLine($$"""
                    /// <summary>Updates the row with this entity's primary key, and returns whether a row was changed.</summary>
                    public static bool Update(this {{Context}} context, {{model.FullTypeName}} entity)
                    {
            {{GuardNull(model)}}
                        global::DataVo.Core.Contracts.Results.QueryResult result = StatementsFor(context).Update!.Execute(new {{Parameter}}[] { {{arguments}}, {{ParameterExpression(key, "key", $"entity.{key.PropertyName}")}} });
                        {{Support}}.ThrowIfError(result, "Update {{model.ModelName}}");
                        return {{Support}}.ChangedAnyRow(result);
                    }
            """);
    }

    private static string GuardNull(TableModel model) => model.IsReferenceType
        ? "            if (entity is null)\n            {\n                throw new global::System.ArgumentNullException(nameof(entity));\n            }\n"
        : string.Empty;

    private static string ParameterExpression(ColumnModel column, string name, string value)
    {
        if (column.Type.UsesObjectParameter)
        {
            return $"{Parameter}.FromObject(\"{name}\", {value})";
        }

        if (!column.IsNullable)
        {
            return $"new {Parameter}(\"{name}\", {value})";
        }

        string present = column.Type.IsValueType ? $"{value}.Value" : value;
        return $"{value} is null ? {Parameter}.Null(\"{name}\") : new {Parameter}(\"{name}\", {present})";
    }
}
