using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using DataVo.Core.Constants;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.VectorData;

namespace DataVo.VectorData;

/// <summary>What a property of a record is: the key, a data value, or a vector.</summary>
internal enum DataVoPropertyRole
{
    Key,
    Data,
    Vector,
}

/// <summary>How a vector property holds its floats on the record.</summary>
internal enum DataVoVectorKind
{
    /// <summary><see cref="ReadOnlyMemory{T}"/> of <see cref="float"/> (or its nullable form).</summary>
    Memory,

    /// <summary>A <see cref="float"/> array.</summary>
    Array,

    /// <summary><see cref="Embedding{T}"/> of <see cref="float"/>.</summary>
    Embedding,

    /// <summary>
    /// A value (such as a <see cref="string"/>) the collection's embedding generator turns into the stored vector.
    /// The record keeps its input; the vector is never read back into it.
    /// </summary>
    Generated,
}

/// <summary>One mapped property: its record name, its column, its CLR type and its role-specific settings.</summary>
internal sealed class DataVoPropertyModel
{
    public required string Name { get; init; }

    /// <summary>The column the property is stored in.</summary>
    public required string Column { get; init; }

    public required DataVoPropertyRole Role { get; init; }

    /// <summary>The property's declared type.</summary>
    public required Type Type { get; init; }

    /// <summary>The CLR property of a typed record; null for dynamic (dictionary) records.</summary>
    public PropertyInfo? Property { get; init; }

    /// <summary>The DataVo SQL column type.</summary>
    public required string SqlType { get; init; }

    /// <summary>Whether a data property gets a B-tree index.</summary>
    public bool IsIndexed { get; init; }

    /// <summary>Whether a <see cref="Guid"/> key is generated on upsert when the record holds <see cref="Guid.Empty"/>.</summary>
    public bool IsAutoGenerated { get; init; }

    public int Dimensions { get; init; }

    /// <summary>A <see cref="Microsoft.Extensions.VectorData.DistanceFunction"/> name.</summary>
    public string DistanceFunction { get; init; } = Microsoft.Extensions.VectorData.DistanceFunction.CosineDistance;

    /// <summary>An <see cref="Microsoft.Extensions.VectorData.IndexKind"/> name.</summary>
    public string IndexKind { get; init; } = Microsoft.Extensions.VectorData.IndexKind.Hnsw;

    public DataVoVectorKind VectorKind { get; init; }

    /// <summary>The generator of a <see cref="DataVoVectorKind.Generated"/> vector property.</summary>
    public IEmbeddingGenerator? EmbeddingGenerator { get; init; }

    /// <summary>The DataVo distance operator for this vector's metric.</summary>
    public string DistanceOperator =>
        DistanceFunction is Microsoft.Extensions.VectorData.DistanceFunction.EuclideanDistance or Microsoft.Extensions.VectorData.DistanceFunction.EuclideanSquaredDistance ? "<->" : "<=>";

    /// <summary>The DataVo index metric for this vector's distance function.</summary>
    public string IndexMetric =>
        DistanceFunction is Microsoft.Extensions.VectorData.DistanceFunction.EuclideanDistance or Microsoft.Extensions.VectorData.DistanceFunction.EuclideanSquaredDistance ? "euclidean" : "cosine";
}

/// <summary>
/// The mapping between a record type (or a <see cref="VectorStoreCollectionDefinition"/>) and a DataVo table: one key
/// column, data columns and <c>VECTOR(n)</c> columns, read from <see cref="VectorStoreKeyAttribute"/>,
/// <see cref="VectorStoreDataAttribute"/> and <see cref="VectorStoreVectorAttribute"/> or from the definition.
/// </summary>
internal sealed class DataVoCollectionModel
{
    private readonly Dictionary<string, DataVoPropertyModel> _byName;

    private DataVoCollectionModel(DataVoPropertyModel key, List<DataVoPropertyModel> data, List<DataVoPropertyModel> vectors)
    {
        Key = key;
        Data = data;
        Vectors = vectors;
        All = [key, .. data, .. vectors];
        _byName = All.ToDictionary(property => property.Name, StringComparer.Ordinal);
        ValidateColumns();
    }

    public DataVoPropertyModel Key { get; }

    public IReadOnlyList<DataVoPropertyModel> Data { get; }

    public IReadOnlyList<DataVoPropertyModel> Vectors { get; }

    /// <summary>Key, data and vector properties, in that order (the table's column order).</summary>
    public IReadOnlyList<DataVoPropertyModel> All { get; }

    /// <summary>The property named <paramref name="name"/> (its record name, not its column).</summary>
    public bool TryGetProperty(string name, [NotNullWhen(true)] out DataVoPropertyModel? property) => _byName.TryGetValue(name, out property);

    /// <summary>The vector property a search ranks by: the one named, or the only one.</summary>
    public DataVoPropertyModel ResolveVector(string? name)
    {
        if (name is not null)
        {
            return TryGetProperty(name, out DataVoPropertyModel? named) && named.Role == DataVoPropertyRole.Vector
                ? named
                : throw new InvalidOperationException($"'{name}' is not a vector property of the collection.");
        }

        return Vectors.Count switch
        {
            1 => Vectors[0],
            0 => throw new InvalidOperationException("The collection has no vector property to search."),
            _ => throw new InvalidOperationException("The collection has more than one vector property; set VectorSearchOptions.VectorProperty."),
        };
    }

    /// <summary>
    /// Builds the model of typed records: from the attributes on <paramref name="recordType"/>'s public properties,
    /// or from <paramref name="definition"/> when given (its properties bound to the record's by name).
    /// </summary>
    public static DataVoCollectionModel Build(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties)] Type recordType,
        VectorStoreCollectionDefinition? definition,
        IEmbeddingGenerator? defaultGenerator)
    {
        PropertyInfo[] properties = recordType.GetProperties(BindingFlags.Public | BindingFlags.Instance);
        if (definition is not null)
        {
            return FromDefinition(definition, defaultGenerator, name =>
                Array.Find(properties, property => property.Name == name)
                    ?? throw new InvalidOperationException($"The definition names '{name}', which is not a public property of {recordType.Name}."));
        }

        DataVoPropertyModel? key = null;
        var data = new List<DataVoPropertyModel>();
        var vectors = new List<DataVoPropertyModel>();
        foreach (PropertyInfo property in properties)
        {
            if (property.GetCustomAttribute<VectorStoreKeyAttribute>() is { } keyAttribute)
            {
                if (key is not null)
                {
                    throw new InvalidOperationException($"{recordType.Name} has more than one [VectorStoreKey] property.");
                }

                key = CreateKey(property.Name, keyAttribute.StorageName, property.PropertyType, property, ExplicitAutoGenerated(property, keyAttribute));
            }
            else if (property.GetCustomAttribute<VectorStoreDataAttribute>() is { } dataAttribute)
            {
                RejectFullTextIndex(property.Name, dataAttribute.IsFullTextIndexed);
                data.Add(CreateData(property.Name, dataAttribute.StorageName, property.PropertyType, property, dataAttribute.IsIndexed));
            }
            else if (property.GetCustomAttribute<VectorStoreVectorAttribute>() is { } vectorAttribute)
            {
                vectors.Add(CreateVector(property.Name, vectorAttribute.StorageName, property.PropertyType, property, vectorAttribute.Dimensions,
                    vectorAttribute.DistanceFunction, vectorAttribute.IndexKind, generator: null, defaultGenerator));
            }
        }

        return new DataVoCollectionModel(
            key ?? throw new InvalidOperationException($"{recordType.Name} has no [VectorStoreKey] property."),
            data,
            vectors);
    }

    /// <summary>Builds the model of dynamic (dictionary) records from <paramref name="definition"/>.</summary>
    public static DataVoCollectionModel BuildDynamic(VectorStoreCollectionDefinition definition, IEmbeddingGenerator? defaultGenerator) =>
        FromDefinition(definition, defaultGenerator, propertyOf: null);

    private static DataVoCollectionModel FromDefinition(VectorStoreCollectionDefinition definition, IEmbeddingGenerator? defaultGenerator, Func<string, PropertyInfo>? propertyOf)
    {
        IEmbeddingGenerator? generator = definition.EmbeddingGenerator ?? defaultGenerator;
        DataVoPropertyModel? key = null;
        var data = new List<DataVoPropertyModel>();
        var vectors = new List<DataVoPropertyModel>();
        foreach (VectorStoreProperty property in definition.Properties)
        {
            PropertyInfo? clr = propertyOf?.Invoke(property.Name);
            Type type = property.Type ?? clr?.PropertyType
                ?? throw new InvalidOperationException($"Property '{property.Name}' of the definition has no type.");
            switch (property)
            {
                case VectorStoreKeyProperty keyProperty:
                    if (key is not null)
                    {
                        throw new InvalidOperationException("The definition has more than one key property.");
                    }

                    key = CreateKey(property.Name, property.StorageName, type, clr, keyProperty.IsAutoGenerated);
                    break;
                case VectorStoreDataProperty dataProperty:
                    RejectFullTextIndex(property.Name, dataProperty.IsFullTextIndexed);
                    data.Add(CreateData(property.Name, property.StorageName, type, clr, dataProperty.IsIndexed));
                    break;
                case VectorStoreVectorProperty vectorProperty:
                    vectors.Add(CreateVector(property.Name, property.StorageName, type, clr, vectorProperty.Dimensions,
                        vectorProperty.DistanceFunction, vectorProperty.IndexKind, vectorProperty.EmbeddingGenerator, generator));
                    break;
                default:
                    throw new InvalidOperationException($"Property '{property.Name}' of the definition is not a key, data or vector property.");
            }
        }

        return new DataVoCollectionModel(key ?? throw new InvalidOperationException("The definition has no key property."), data, vectors);
    }

    /// <summary>
    /// The key attribute's <c>IsAutoGenerated</c> when the record set it, or null when it was left unset (Guid keys are
    /// then generated). The attribute keeps that distinction only in its internal nullable <c>IsAutoGeneratedNullable</c>
    /// property, which <see cref="DynamicDependencyAttribute"/> keeps under trimming; should a later abstractions release
    /// drop it, the named argument recorded in the property's attribute metadata (public API) answers instead, so
    /// <c>[VectorStoreKey(IsAutoGenerated = false)]</c> is never silently read as unset.
    /// </summary>
    [DynamicDependency(DynamicallyAccessedMemberTypes.NonPublicProperties, typeof(VectorStoreKeyAttribute))]
    private static bool? ExplicitAutoGenerated(PropertyInfo property, VectorStoreKeyAttribute attribute)
    {
        if (typeof(VectorStoreKeyAttribute).GetProperty(AutoGeneratedNullableProperty, BindingFlags.Instance | BindingFlags.NonPublic) is { } nullable)
        {
            return nullable.GetValue(attribute) as bool?;
        }

        foreach (CustomAttributeData data in property.GetCustomAttributesData())
        {
            if (data.AttributeType != typeof(VectorStoreKeyAttribute))
            {
                continue;
            }

            foreach (CustomAttributeNamedArgument argument in data.NamedArguments)
            {
                if (argument.MemberName == nameof(VectorStoreKeyAttribute.IsAutoGenerated) && argument.TypedValue.Value is bool value)
                {
                    return value;
                }
            }
        }

        return null;
    }

    /// <summary>The internal property of <see cref="VectorStoreKeyAttribute"/> that tells an explicit <c>IsAutoGenerated</c> from an unset one.</summary>
    internal const string AutoGeneratedNullableProperty = "IsAutoGeneratedNullable";

    /// <summary>Rejects <c>IsFullTextIndexed</c>: DataVo has no full-text index, and ignoring the request would hide that.</summary>
    private static void RejectFullTextIndex(string name, bool isFullTextIndexed)
    {
        if (isFullTextIndexed)
        {
            throw new NotSupportedException(
                $"Data property '{name}' sets IsFullTextIndexed: DataVo has no full-text index (hybrid keyword search is not supported). Use IsIndexed for a B-tree index.");
        }
    }

    private static DataVoPropertyModel CreateKey(string name, string? storageName, Type type, PropertyInfo? property, bool? autoGenerated)
    {
        string sqlType = type == typeof(int) ? "INT"
            : type == typeof(long) ? "BIGINT"
            : type == typeof(Guid) ? "GUID"
            : type == typeof(string) ? "VARCHAR"
            : type == typeof(object) ? "VARCHAR" // a dynamic collection without a key type; strings are accepted
            : throw new NotSupportedException($"Key property '{name}' is a {type.Name}; DataVo keys are int, long, Guid or string.");
        if (autoGenerated == true && type != typeof(Guid))
        {
            throw new NotSupportedException($"Key property '{name}': DataVo generates only Guid keys.");
        }

        return new DataVoPropertyModel
        {
            Name = name,
            Column = ColumnName(name, storageName),
            Role = DataVoPropertyRole.Key,
            Type = type,
            Property = property,
            SqlType = sqlType,
            IsAutoGenerated = type == typeof(Guid) && autoGenerated != false,
        };
    }

    private static DataVoPropertyModel CreateData(string name, string? storageName, Type type, PropertyInfo? property, bool isIndexed) => new()
    {
        Name = name,
        Column = ColumnName(name, storageName),
        Role = DataVoPropertyRole.Data,
        Type = type,
        Property = property,
        SqlType = DataVoValueMapper.SqlTypeOf(type)
            ?? throw new NotSupportedException($"Data property '{name}' is a {type.Name}, which DataVo cannot store."),
        IsIndexed = isIndexed,
    };

    private static DataVoPropertyModel CreateVector(
        string name,
        string? storageName,
        Type type,
        PropertyInfo? property,
        int dimensions,
        string? distanceFunction,
        string? indexKind,
        IEmbeddingGenerator? generator,
        IEmbeddingGenerator? defaultGenerator)
    {
        if (dimensions <= 0)
        {
            throw new InvalidOperationException($"Vector property '{name}' must declare a positive number of dimensions.");
        }

        Type underlying = Nullable.GetUnderlyingType(type) ?? type;
        DataVoVectorKind kind = underlying == typeof(ReadOnlyMemory<float>) ? DataVoVectorKind.Memory
            : underlying == typeof(float[]) ? DataVoVectorKind.Array
            : underlying == typeof(Embedding<float>) ? DataVoVectorKind.Embedding
            : underlying == typeof(string) ? DataVoVectorKind.Generated
            : throw new NotSupportedException(
                $"Vector property '{name}' is a {type.Name}: use ReadOnlyMemory<float>, float[] or Embedding<float>, or a string embedded by an IEmbeddingGenerator<string, Embedding<float>>.");
        // Every vector kind keeps the configured generator: pre-embedded properties need it to search by text.
        IEmbeddingGenerator? embeddingGenerator = generator ?? defaultGenerator;
        if (kind == DataVoVectorKind.Generated && embeddingGenerator is null)
        {
            throw new NotSupportedException(
                $"Vector property '{name}' is a string: configure an IEmbeddingGenerator<string, Embedding<float>> on the store, the definition or the property.");
        }

        string distance = distanceFunction ?? Microsoft.Extensions.VectorData.DistanceFunction.CosineDistance;
        if (distance is not (Microsoft.Extensions.VectorData.DistanceFunction.CosineDistance
            or Microsoft.Extensions.VectorData.DistanceFunction.CosineSimilarity
            or Microsoft.Extensions.VectorData.DistanceFunction.EuclideanDistance
            or Microsoft.Extensions.VectorData.DistanceFunction.EuclideanSquaredDistance))
        {
            throw new NotSupportedException(
                $"Vector property '{name}': DataVo supports the CosineDistance, CosineSimilarity, EuclideanDistance and EuclideanSquaredDistance functions, not {distance}.");
        }

        string index = indexKind ?? Microsoft.Extensions.VectorData.IndexKind.Hnsw;
        if (index is not (Microsoft.Extensions.VectorData.IndexKind.Hnsw or Microsoft.Extensions.VectorData.IndexKind.Flat))
        {
            throw new NotSupportedException($"Vector property '{name}': DataVo supports the Hnsw and Flat index kinds, not {index}.");
        }

        return new DataVoPropertyModel
        {
            Name = name,
            Column = ColumnName(name, storageName),
            Role = DataVoPropertyRole.Vector,
            Type = type,
            Property = property,
            SqlType = $"VECTOR({dimensions})",
            Dimensions = dimensions,
            DistanceFunction = distance,
            IndexKind = index,
            VectorKind = kind,
            EmbeddingGenerator = embeddingGenerator,
        };
    }

    /// <summary>
    /// The column for a property: its storage name, else its name. DataVo SQL has no quoted identifiers, so a name
    /// that is a reserved word (such as <c>Vector</c>, a common property name) gets a trailing underscore.
    /// </summary>
    private static string ColumnName(string name, string? storageName)
    {
        string column = storageName ?? name;
        DataVoSqlNames.ValidateIdentifier(column, "column");
        return SqlKeywords.All.Contains(column.ToUpperInvariant()) ? column + "_" : column;
    }

    private void ValidateColumns()
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (DataVoPropertyModel property in All)
        {
            if (!seen.Add(property.Column))
            {
                throw new InvalidOperationException($"Two properties map to the column '{property.Column}'.");
            }
        }
    }
}
