using Microsoft.Extensions.VectorData;

namespace DataVo.VectorData.Tests;

/// <summary>Two vector properties with different metrics and index kinds, and custom storage names.</summary>
public sealed class MultiVectorDoc
{
    [VectorStoreKey]
    public int Id { get; set; }

    [VectorStoreData(StorageName = "title_text", IsIndexed = true)]
    public string Title { get; set; } = "";

    [VectorStoreVector(3, StorageName = "title_vec", DistanceFunction = DistanceFunction.CosineSimilarity)]
    public ReadOnlyMemory<float> TitleVector { get; set; }

    [VectorStoreVector(2, StorageName = "body_vec", DistanceFunction = DistanceFunction.EuclideanDistance, IndexKind = IndexKind.Flat)]
    public float[]? BodyVector { get; set; }
}

/// <summary>A Guid key the application assigns: <c>IsAutoGenerated = false</c> must keep <see cref="Guid.Empty"/>.</summary>
public sealed class ManualGuidDoc
{
    [VectorStoreKey(IsAutoGenerated = false)]
    public Guid Id { get; set; }

    [VectorStoreData]
    public string Name { get; set; } = "";

    [VectorStoreVector(2)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>A Guid key with the attribute's default: generated when empty.</summary>
public sealed class DefaultGuidDoc
{
    [VectorStoreKey]
    public Guid Id { get; set; }

    [VectorStoreVector(2)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>A data property of a type DataVo cannot store.</summary>
public sealed class UnsupportedTypeDoc
{
    [VectorStoreKey]
    public int Id { get; set; }

    [VectorStoreData]
    public TimeSpan Duration { get; set; }

    [VectorStoreVector(2)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>Every further CLR data type the mapper stores: DateOnly, DateTimeOffset, decimal, short, byte, float, List&lt;string&gt;, Guid.</summary>
public sealed class TypedDataDoc
{
    [VectorStoreKey]
    public int Id { get; set; }

    [VectorStoreData]
    public DateOnly Day { get; set; }

    [VectorStoreData]
    public DateTimeOffset At { get; set; }

    [VectorStoreData]
    public decimal Price { get; set; }

    [VectorStoreData]
    public short Small { get; set; }

    [VectorStoreData]
    public byte Tiny { get; set; }

    [VectorStoreData]
    public float Ratio { get; set; }

    [VectorStoreData]
    public List<string> Labels { get; set; } = [];

    [VectorStoreData]
    public Guid Ref { get; set; }

    [VectorStoreVector(2)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>Asks for a full-text index, which DataVo does not have.</summary>
public sealed class FullTextDoc
{
    [VectorStoreKey]
    public int Id { get; set; }

    [VectorStoreData(IsFullTextIndexed = true)]
    public string Body { get; set; } = "";

    [VectorStoreVector(2)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>A pre-embedded vector sized for <see cref="TestEmbeddingGenerator"/>, so text searches go through it.</summary>
public sealed class PreEmbeddedDoc
{
    [VectorStoreKey]
    public int Id { get; set; }

    [VectorStoreData]
    public string Text { get; set; } = "";

    [VectorStoreVector(TestEmbeddingGenerator.Dimensions)]
    public ReadOnlyMemory<float> Vector { get; set; }
}

/// <summary>A record without attributes, mapped only by a typed <see cref="VectorStoreCollectionDefinition"/>.</summary>
public sealed class PlainDoc
{
    public string Code { get; set; } = "";

    public int Size { get; set; }

    public ReadOnlyMemory<float> Embedding { get; set; }
}
